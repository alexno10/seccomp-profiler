package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strconv"
	"strings"
)

type entry struct {
	nr   int
	name string
}

func main() {
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		panic("failed to resolve caller path for internal/syscalls/gen")
	}
	genDir := filepath.Dir(thisFile)
	syscallsDir := filepath.Dir(genDir)

	amd64, err := parseTbl(filepath.Join(genDir, "syscall_64.tbl"))
	if err != nil {
		panic(err)
	}
	arm64, err := parseHeader(filepath.Join(genDir, "unistd_arm64.h"))
	if err != nil {
		panic(err)
	}
	// Go treats *_amd64.go and *_arm64.go as mutually exclusive GOARCH build constraints.
	// Emit both tables into each file so cross-arch lookups (e.g. ArchARM64 on an amd64 host) work on both target architectures.
	if err := writeTables(filepath.Join(syscallsDir, "zsyscalls_amd64.go"), amd64, arm64); err != nil {
		panic(err)
	}
	if err := writeTables(filepath.Join(syscallsDir, "zsyscalls_arm64.go"), amd64, arm64); err != nil {
		panic(err)
	}
}

func parseTbl(path string) ([]entry, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	var out []entry
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 3 {
			continue
		}
		nr, err := strconv.Atoi(fields[0])
		if err != nil || nr < 0 || nr >= 512 {
			continue
		}
		abi := fields[1]
		if abi == "x32" {
			continue
		}
		out = append(out, entry{nr: nr, name: fields[2]})
	}
	return out, sc.Err()
}

func parseHeader(path string) ([]entry, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	var out []entry
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if !strings.HasPrefix(line, "#define __NR_") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 3 {
			continue
		}
		name := strings.TrimPrefix(fields[1], "__NR_")
		if name == "syscalls" {
			continue
		}
		nr, err := strconv.Atoi(fields[2])
		if err != nil || nr < 0 || nr >= 512 {
			continue
		}
		out = append(out, entry{nr: nr, name: name})
	}
	return out, sc.Err()
}

func writeTables(filename string, amd64, arm64 []entry) error {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by internal/syscalls/gen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package syscalls\n\n")
	writeSingleMap(&buf, "amd64", amd64)
	fmt.Fprintf(&buf, "\n")
	writeSingleMap(&buf, "arm64", arm64)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filename, formatted, 0o644)
}

func writeSingleMap(buf *bytes.Buffer, suffix string, entries []entry) {
	sort.Slice(entries, func(i, j int) bool { return entries[i].nr < entries[j].nr })
	fmt.Fprintf(buf, "var nameByNr_%s = map[int]string{\n", suffix)
	for _, e := range entries {
		fmt.Fprintf(buf, "\t%d: %q,\n", e.nr, e.name)
	}
	fmt.Fprintf(buf, "}\n\n")
	fmt.Fprintf(buf, "var nrByName_%s = map[string]int{\n", suffix)
	for _, e := range entries {
		fmt.Fprintf(buf, "\t%q: %d,\n", e.name, e.nr)
	}
	fmt.Fprintf(buf, "}\n")
}
